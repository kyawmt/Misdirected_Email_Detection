# ------------------------------------------------------------------ records


def load_records(root: Path) -> dict:
    root = Path(root)

    def read(path: Path):
        full = root / path
        return json.loads(full.read_text(encoding="utf-8")) if full.exists() else None

    return {
        "scenarios": read(V.SCENARIO_RECORD),
        "bundle": {name: read(path) for name, path in V.BUNDLE_RECORDS.items()},
        "reads": read(V.READS_RECORD),
        "images": read(V.IMAGES_RECORD),
        "runs": (read(V.RUNS_RECORD) or {}).get("runs", {}),
        "rebuild": read(V.REBUILD_RECORD),
        "digests": read(V.DIGESTS_RECORD),
        "mutations": read(V.MUTATION_RECORD),
        "clean": read(V.CLEAN_CHECKOUT_RECORD),
        "smoke": {name: read(path) for name, path in V.SMOKE_RECORDS.items()},
        "latency": read(V.LATENCY_RECORD),
        "phase6_latency": read(Path(V.LATENCY_PATH)),
        "rehearsal": {name: read(path) for name, path in V.REHEARSAL_RECORDS.items()},
        "browser": read(V.BROWSER_RECORD),
        "platform": read(V.PLATFORM_RECORD),
    }


# ------------------------------------------------------------------ formatting


def _table(headers: list[str], rows: list[list]) -> str:
    def cell(value) -> str:
        return str(value).replace("|", "\\|").replace("\n", " ")

    lines = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    lines += ["| " + " | ".join(cell(item) for item in row) + " |" for row in rows]
    return "\n".join(lines)


def _when(stamp: str | None) -> str:
    return stamp.replace("T", " ").replace("Z", " UTC") if stamp else "not run"


def _ms(value: float) -> str:
    return f"{value:.2f} ms"


def _minutes(seconds: float) -> str:
    whole = int(round(seconds))
    return f"{seconds:.1f} s ({whole // 60}m{whole % 60:02d}s)" if whole >= 60 else f"{seconds:.1f} s"


def _score(value: float) -> str:
    return f"{value:.7f}" if value >= 1e-3 else f"{value:.3e}"


def _mib(size: int | None) -> str:
    return "not reported" if size is None else f"{size / 2**20:.0f} MiB"


def _counts(run: dict) -> str:
    parts = [f"{run[key]} {label}" for key, label in (("passed", "passed"), ("failed", "failed"), ("errors", "errors"), ("skipped", "skipped"), ("deselected", "deselected"), ("checks_passed", "checks passed")) if key in run]
    return ", ".join(parts) or run.get("summary_line") or "no summary line"


def _storage(info: dict | None) -> str:
    if not info:
        return "pandas not installed"
    return f"option `{info['option']}`, dtype `{info['series_dtype']}`, held in `{info.get('backend', 'unknown')}`"


def _kv(counts: dict) -> str:
    """{'assessed': 1000} as `assessed 1000`."""
    return ", ".join(f"{key} {value}" for key, value in counts.items()) or "none"


def _ports(ports: dict) -> str:
    return ", ".join(f"{inside} to {' and '.join(outside)}" for inside, outside in ports.items()) or "none"


def _status(ok: bool | None) -> str:
    return {True: "passed", False: "FAILED", None: "not run"}[ok]


def _missing(name: str) -> str:
    return f"_Not run: the record `{name}` does not exist._\n"


