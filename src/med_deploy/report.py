def write_documents(root: Path, out_dir: Path = V.DOCS_DIR) -> list[Path]:
    root = Path(root)
    target = root / out_dir
    target.mkdir(parents=True, exist_ok=True)
    written = []
    for name, text in documents(root).items():
        path = target / name
        path.write_text(text.rstrip("\n") + "\n", encoding="utf-8")
        written.append(path)
    return written
